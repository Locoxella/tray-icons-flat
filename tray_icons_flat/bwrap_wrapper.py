"""
Bubblewrap (bwrap) sandbox wrapper generator and process manager for tray-icons-flat.
Enables overriding hardcoded icon paths in closed-source binaries without root privileges.
"""

import os
import shutil
import subprocess
import time
from typing import Dict, List, Optional


class BwrapWrapper:
    """Manages creation, installation, and removal of bwrap sandbox wrappers."""

    @staticmethod
    def get_bwrap_path() -> str:
        """Finds bwrap executable path."""
        which_bwrap = shutil.which("bwrap")
        return which_bwrap if which_bwrap else "/usr/bin/bwrap"

    @classmethod
    def generate_wrapper_script(
        cls,
        target_binary: str,
        bind_mounts: Dict[str, str],
        bwrap_path: Optional[str] = None
    ) -> str:
        """
        Generates shell wrapper script content utilizing bwrap --ro-bind overlays.
        `bind_mounts` maps target filesystem paths to replacement icon files.
        """
        bwrap_bin = bwrap_path or cls.get_bwrap_path()
        bind_args = []
        for target_path, source_path in bind_mounts.items():
            bind_args.append(f'--ro-bind "{source_path}" "{target_path}"')

        binds_str = " \\\n  ".join(bind_args)
        if binds_str:
            binds_str = f"  {binds_str} \\\n"

        return f"""#!/bin/sh
# Wrapper generated by tray-icons-flat
exec {bwrap_bin} --dev-bind / / \\
{binds_str}  "{target_binary}" "$@"
"""

    @classmethod
    def graceful_restart(cls, process_name: str, new_exec: str, timeout: float = 1.5) -> bool:
        """
        Gracefully restarts a process by sending SIGTERM, waiting for termination,
        falling back to SIGKILL if necessary, and launching the new executable.
        """
        # Check if process is running
        is_running = False
        if shutil.which("killall"):
            check = subprocess.run(["killall", "-0", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            is_running = (check.returncode == 0)
        elif shutil.which("pkill"):
            check = subprocess.run(["pkill", "-0", "-x", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            is_running = (check.returncode == 0)

        if not is_running:
            return False

        # Attempt graceful termination (SIGTERM)
        if shutil.which("killall"):
            subprocess.run(["killall", "-15", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        elif shutil.which("pkill"):
            subprocess.run(["pkill", "-15", "-x", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

        # Wait for termination
        start = time.time()
        terminated = False
        while time.time() - start < timeout:
            time.sleep(0.1)
            if shutil.which("killall"):
                c = subprocess.run(["killall", "-0", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                if c.returncode != 0:
                    terminated = True
                    break
            elif shutil.which("pkill"):
                c = subprocess.run(["pkill", "-0", "-x", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                if c.returncode != 0:
                    terminated = True
                    break

        # Force kill if still running after timeout
        if not terminated:
            if shutil.which("killall"):
                subprocess.run(["killall", "-9", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            elif shutil.which("pkill"):
                subprocess.run(["pkill", "-9", "-x", process_name], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            time.sleep(0.2)

        # Launch replacement in new background session
        try:
            subprocess.Popen([new_exec], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)
            return True
        except Exception:
            return False

    @classmethod
    def install(
        cls,
        target_binary: str,
        wrapper_bin: str,
        bind_mounts: Dict[str, str],
        desktop_files: Optional[List[str]] = None,
        desktop_name: Optional[str] = None,
        desktop_icon: Optional[str] = None,
        desktop_comment: Optional[str] = None,
        restart_process: bool = True
    ) -> List[str]:
        """
        Installs the bwrap wrapper binary and configures desktop overrides.
        Returns list of created desktop file paths.
        """
        os.makedirs(os.path.dirname(os.path.abspath(wrapper_bin)), exist_ok=True)
        script_content = cls.generate_wrapper_script(target_binary, bind_mounts)
        with open(wrapper_bin, "w", encoding="utf-8") as wf:
            wf.write(script_content)
        os.chmod(wrapper_bin, 0o755)

        updated_desktops = []
        if desktop_files:
            entry_content = f"""[Desktop Entry]
Type=Application
Name={desktop_name or os.path.basename(target_binary)}
Exec={wrapper_bin}
Icon={desktop_icon or 'application-x-executable'}
Comment={desktop_comment or 'Wrapped by tray-icons-flat'}
Terminal=false
"""
            for df in desktop_files:
                os.makedirs(os.path.dirname(os.path.abspath(df)), exist_ok=True)
                with open(df, "w", encoding="utf-8") as f:
                    f.write(entry_content)
                updated_desktops.append(df)

        if restart_process:
            bin_name = os.path.basename(target_binary)
            cls.graceful_restart(bin_name, wrapper_bin)

        return updated_desktops

    @classmethod
    def uninstall(
        cls,
        wrapper_bin: str,
        desktop_files: Optional[List[str]] = None,
        target_binary: Optional[str] = None,
        restart_process: bool = True
    ) -> bool:
        """Removes the wrapper script and desktop overrides, reverting back to target_binary."""
        if os.path.exists(wrapper_bin):
            try:
                os.remove(wrapper_bin)
            except OSError:
                pass

        if desktop_files:
            for df in desktop_files:
                if os.path.exists(df):
                    try:
                        os.remove(df)
                    except OSError:
                        pass

        if restart_process and target_binary:
            bin_name = os.path.basename(target_binary)
            cls.graceful_restart(bin_name, target_binary)

        return True
